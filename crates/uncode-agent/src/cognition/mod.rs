//! 认知层 — LLM 的"自由之地"
//!
//! ## 认知显化与决策驱动设计中的定位
//!
//! 认知层回答一个问题：**"接下来可以做什么？"**
//!
//! 它负责理解任务、召回知识、推理方案、生成候选行动。
//! 认知层的输出是 `ActionProposal`（候选方案），而非最终命令——
//! 最终的合法性判定由决策层（`decision/`）负责。
//!
//! ## 模块结构
//!
//! | 模块 | 职责 | 状态 |
//! |:---|:---|:---|
//! | `prompt_manager` | 系统提示词 + 工具描述生成 | ★ 已实现 |
//! | `uncertainty` | 不确定性三分类显式建模 | ★ 已实现 |
//! | `memory` | 压缩边界管理 + 摘要注入策略 | ★ 已实现 |
//! | `episode` | 情景记忆 — 按重要性评分的事件记忆 ★ 新增 |
//! | `working_memory` | 工作记忆 — turn 内 scratchpad ★ 新增 |
//!
//! ## 三层记忆架构
//!
//! ```text
//! ┌──────────────────────┐
//! │  WorkingMemory       │  turn 内临时 scratchpad
//! │  (观察/决策/假设/待办) │  每个 turn 清空 → 重要条目转入 EpisodeMemory
//! └──────────┬───────────┘
//!            │ flush
//!            ▼
//! ┌──────────────────────┐
//! │  EpisodeMemory       │  按重要性评分保留
//! │  (事件 + 重要性分数)   │  驱逐低分条目，构建 LLM 上下文摘要
//! └──────────┬───────────┘
//!            │ 摘要注入
//!            ▼
//! ┌──────────────────────┐
//! │  MemoryManager       │  压缩决策 + 上下文窗口
//! │  (CompactionDecision) │  阈值触发 → compact_session
//! └──────────────────────┘
//!            │
//!            ▼
//! ┌──────────────────────┐
//! │  SessionStore        │  治理层 — 事件溯源
//! │  (不可变追加日志)      │  永不删除
//! └──────────────────────┘
//! ```
//!
//! ## 范式引用
//!
//! 参见 `docs/ai-agent-archi/cognition-decision-driven-design.md` §3.3
//! "认知层回答'接下来可以做什么'，决策层回答'哪些可以做、做了什么、结果怎样'"

pub mod episode; // ★ 情景记忆
